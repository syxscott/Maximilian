#!/usr/bin/env node
// scripts/audit-deprecated.js
//
// Find every @deprecated and @experimental JSDoc tag in the source and
// produce a Markdown report grouped by package. Used by `pnpm report:deprecation`.
//
// Format expectation (per docs/DEPRECATION.md):
//   /** @deprecated since 0.2.0, removal 0.5.0 — use newName() instead */
//   export function oldName() { ... }
//
//   /** @experimental — API may change without notice */
//   export class NovelThing { ... }

import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs"
import { join, relative, sep } from "node:path"

const ROOT = process.cwd()
const SRC_DIRS = ["packages", "apps"]
const REPORT_PATH = join(ROOT, "docs", "DEPRECATION-audit.md")

const findings = {
  deprecated: [],
  experimental: [],
}

/** @param {string} dir */
function walk(dir) {
  let entries
  try {
    entries = readdirSync(dir)
  } catch {
    return
  }
  for (const entry of entries) {
    if (entry === "node_modules" || entry === "dist" || entry === ".turbo" || entry === "coverage") continue
    const full = join(dir, entry)
    const s = statSync(full)
    if (s.isDirectory()) {
      walk(full)
    } else if (/\.(ts|tsx|mts)$/.test(entry)) {
      scan(full)
    }
  }
}

/** @param {string} file */
function scan(file) {
  const text = readFileSync(file, "utf8")
  const lines = text.split("\n")
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i]
    if (line.includes("@deprecated")) {
      findings.deprecated.push({ file, line: i + 1, text: line.trim() })
    }
    if (line.includes("@experimental")) {
      findings.experimental.push({ file, line: i + 1, text: line.trim() })
    }
  }
}

for (const d of SRC_DIRS) {
  walk(join(ROOT, d))
}

const sections = []
sections.push(`# Deprecation & Experimental API Audit\n`)
sections.push(`Generated by \`scripts/audit-deprecated.js\` — do not edit by hand.\n`)
sections.push(`Total: **${findings.deprecated.length}** @deprecated, **${findings.experimental.length}** @experimental.\n`)

function groupByPackage(items) {
  const grouped = new Map()
  for (const it of items) {
    const rel = relative(ROOT, it.file).split(sep)
    const pkg = rel[1] // packages/<pkg>/... or apps/<app>/...
    const arr = grouped.get(pkg) ?? []
    arr.push(it)
    grouped.set(pkg, arr)
  }
  return grouped
}

for (const [kind, list] of [["@deprecated", findings.deprecated], ["@experimental", findings.experimental]]) {
  sections.push(`\n## ${kind}\n`)
  const grouped = groupByPackage(list)
  if (grouped.size === 0) {
    sections.push(`_none_\n`)
    continue
  }
  for (const [pkg, items] of [...grouped.entries()].sort()) {
    sections.push(`\n### ${pkg} (${items.length})\n`)
    for (const it of items) {
      const rel = relative(ROOT, it.file)
      sections.push(`- \`${rel}:${it.line}\` — ${it.text}`)
    }
  }
}

writeFileSync(REPORT_PATH, sections.join("\n"))
console.log(`wrote ${REPORT_PATH}`)
console.log(`  ${findings.deprecated.length} @deprecated`)
console.log(`  ${findings.experimental.length} @experimental`)